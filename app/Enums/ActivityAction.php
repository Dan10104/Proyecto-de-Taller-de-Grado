    case INCIDENCIA_CERRADA = 'INCIDENCIA_CERRADA';
    case MANTENIMIENTO_REGISTRADO = 'MANTENIMIENTO_REGISTRADO';
    case MANTENIMIENTO_CERRADO = 'MANTENIMIENTO_CERRADO';
    case RESERVA_ALERTADA_LIBERACION = 'RESERVA_ALERTADA_LIBERACION';
