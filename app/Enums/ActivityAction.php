    case PRESTAMO_APROBADO = 'PRESTAMO_APROBADO';
    case PRESTAMO_RECHAZADO = 'PRESTAMO_RECHAZADO';
    case PRESTAMO_ENTREGADO = 'PRESTAMO_ENTREGADO';
    case DEVOLUCION_PENDIENTE_REVISION = 'DEVOLUCION_PENDIENTE_REVISION';
    case PRESTAMO_DEVUELTO = 'PRESTAMO_DEVUELTO';
