    case POLITICA_RETIRADA_ESPACIO = 'POLITICA_RETIRADA_ESPACIO';

    public function critical(): bool
    {
        return in_array($this, [self::RESERVA_APROBADA, self::RESERVA_CANCELADA, self::PRESTAMO_ENTREGADO, self::PRESTAMO_DEVUELTO], true);
    }

    public function legacy(): bool
    {
        return in_array($this, array_slice(self::cases(), 0, 18), true);
    }

    public function rejectable(): bool
    {
        return in_array($this, [self::USUARIO_DESHABILITADO, self::ROL_RETIRADO, self::PERMISOS_ROL_ACTUALIZADOS, self::ESPACIO_ESTADO_CAMBIADO, self::EQUIPAMIENTO_ESTADO_CAMBIADO, self::POLITICA_ASIGNADA_ESPACIO, self::POLITICA_RETIRADA_ESPACIO, self::POLITICA_LIBERACION_ACTIVADA, self::SENSOR_CREDENCIAL_CONSULTADA], true);
    }

    public function label(): string
    {
        return ucfirst(mb_strtolower(str_replace('_', ' ', $this->value)));
    }
}
